## كيف نفسّر القيمة؟
- 0.9 فأعلى: ممتاز.
- 0.8 – 0.9: جيد جدًا.
- 0.7 – 0.8: مقبول.
- 0.6 – 0.7: ضعيف (قد يُقبل استكشافيًا).
